static int panel_realme_ab849_prepare(struct drm_panel *panel)
{
	struct panel_realme_ab849 *ctx = to_panel_realme_ab849(panel);
	struct device *dev = &ctx->dsi->dev;
	struct drm_dsc_picture_parameter_set pps;
	int ret;

	ret = regulator_bulk_enable(ARRAY_SIZE(ctx->supplies), ctx->supplies);
	if (ret < 0) {
		dev_err(dev, "Failed to enable regulators: %d\n", ret);
		return ret;
	}

	if (ctx->enable_gpio) {
		gpiod_set_value_cansleep(ctx->enable_gpio, 1);
		msleep(5);
	}

	panel_ab849_reset(ctx);

	ctx->is_boe_p3 = boe_p3;
	if (ctx->is_boe_p3)
		ret = panel_ab849_p3_on(ctx);
	else
		ret = panel_ab849_p1_on(ctx);
	if (ret < 0) {
		dev_err(dev, "Failed to initialize panel: %d\n", ret);
		gpiod_set_value_cansleep(ctx->reset_gpio, 1);
		regulator_bulk_disable(ARRAY_SIZE(ctx->supplies), ctx->supplies);
		return ret;
	}

	drm_dsc_pps_payload_pack(&pps, &ctx->dsc);

	usleep_range(2000, 3000);
	ret = mipi_dsi_picture_parameter_set(ctx->dsi, &pps);
	if (ret < 0) {
		dev_err(dev, "Failed to transmit PPS: %d\n", ret);
		return ret;
	}
	usleep_range(2000, 3000);

	ret = mipi_dsi_compression_mode(ctx->dsi, true);
	if (ret < 0) {
		dev_err(dev, "Failed to enable compression mode: %d\n", ret);
		return ret;
	}

	msleep(28);

	/* Ensure initial visible brightness after display-on */
	ctx->dsi->mode_flags &= ~MIPI_DSI_MODE_LPM;
	ret = mipi_dsi_dcs_set_display_brightness_large(ctx->dsi, 1800);
	ctx->dsi->mode_flags |= MIPI_DSI_MODE_LPM;
	if (ret < 0)
		dev_warn(dev, "Initial brightness write failed: %d\n", ret);

	dev_info(dev, "AB849 panel prepared cleanly (%s)\n",
		 ctx->is_boe_p3 ? "AB849_P_3 (BOE)" : "AB849_P_1_A0022 (Samsung)");

	return 0;
}

static int panel_realme_ab849_unprepare(struct drm_panel *panel)
{
	struct panel_realme_ab849 *ctx = to_panel_realme_ab849(panel);
	struct device *dev = &ctx->dsi->dev;
	int ret;

	if (ctx->is_boe_p3)
		ret = panel_ab849_p3_off(ctx);
	else
		ret = panel_ab849_p1_off(ctx);
	if (ret < 0)
		dev_err(dev, "Failed to un-initialize panel: %d\n", ret);

	gpiod_set_value_cansleep(ctx->reset_gpio, 1);
	if (ctx->enable_gpio)
		gpiod_set_value_cansleep(ctx->enable_gpio, 0);
	regulator_bulk_disable(ARRAY_SIZE(ctx->supplies), ctx->supplies);

	return 0;
}

